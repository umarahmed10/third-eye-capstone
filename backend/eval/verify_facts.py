"""Regenerate the paper's headline confusion matrices from checkpoints.

Why this exists. Three different confusion matrices are currently attributed to
the same n = 1,154 run:

    benchmark_by_tier.json -> overall      455 / 226 / 377 /  96
    PAPER_FACTS "OR-gate (as recorded)"    498 / 356 / 247 /  53
    PAPER_FACTS "noisy-OR (shipped)"       445 / 180 / 423 / 106   <- the paper

The per-tier false positives in the committed JSON (40 + 106 + 80 = 226) match
neither PAPER_FACTS column (shipped 27 + 90 + 63 = 180; OR-gate 85 + 159 + 112
= 356). PAPER_FACTS names benchmark_by_tier.json plus "a shipped replay in
frontend/src/data/benchmark.ts" as the provenance for both of its columns, and
benchmark.ts does contain both 498 and 445 -- but the script that performs the
replay is not in the repository. So the number the paper reports cannot
currently be regenerated by anyone, including us. That is the exact failure the
paper accuses the field of, committed by the paper.

This script is the replay, written down. Point it at a checkpoint directory and
it recomputes BOTH rules from the same rows, per tier and overall, with Wilson
intervals, and diffs the result against a committed report.

Usage:
    python -m eval.verify_facts --checkpoints eval/checkpoints/benchmark/ollama_noarb/0
    python -m eval.verify_facts --checkpoints <dir> --against eval/results/benchmark_by_tier.json
    python -m eval.verify_facts --checkpoints <dir> --tau 0.925 --json out.json

Exit code is 1 on any mismatch, so it can gate CI.

A note on what the two rules ARE, because they are easy to conflate. The OR-gate
flags a contract if any specialist raised a surviving finding. The shipped rule
pools confidences, risk = 1 - prod(1 - conf), and flags at risk >= tau. The
OR-gate is the same formula as tau -> 0, which is why they must never be quoted
interchangeably.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from collections import defaultdict
from pathlib import Path

TIER_ORDER = [
    ("01_safe", "audited_library", "safe"),
    ("01_safe", "audit_reviewed_clean", "safe"),
    ("01_safe", "realworld_no_bug_reported", "safe"),
    ("02_vuln_labelled", "curated", "vulnerable"),
    ("02_vuln_labelled", "injected", "vulnerable"),
    ("02_vuln_labelled", "audit_report", "vulnerable"),
]

DEFAULT_TAU = 0.925


# ---------------------------------------------------------------- statistics

def wilson(k: int, n: int, z: float = 1.959963985) -> tuple[float, float] | None:
    """95% Wilson score interval. Never Wald: Wald's width collapses toward 0
    at the boundaries, and several of these rates sit near one."""
    if n == 0:
        return None
    p = k / n
    d = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, centre - half), min(1.0, centre + half))


def fmt_ci(k: int, n: int) -> str:
    ci = wilson(k, n)
    if ci is None:
        return "—"
    return f"{100 * k / n:5.1f}% [{100 * ci[0]:4.1f}, {100 * ci[1]:4.1f}]"


# ------------------------------------------------------------- the two rules

def or_gate(row: dict) -> bool | None:
    """The historical rule. None = abstention (excluded from scoring)."""
    v = row.get("verdict")
    if v == "NO-GO":
        return True
    if v == "GO":
        return False
    return None


def noisy_or(row: dict, tau: float) -> bool | None:
    """The shipped rule, recomputed from stored per-finding confidences.

    Returns None when the row cannot support the computation -- either it
    abstained, or it is a schema-1 checkpoint that stored only n_findings and
    no confidences. Those two are NOT the same thing and are counted
    separately by the caller: an abstention is a property of the run, a missing
    confidence is a property of the checkpoint format.
    """
    if or_gate(row) is None:
        return None
    findings = row.get("findings")
    if findings is None:
        return None  # schema 1 -- cannot replay
    risk = 1.0
    for f in findings:
        c = f.get("confidence")
        if c is None:
            continue
        risk *= (1.0 - float(c))
    return (1.0 - risk) >= tau


def schema_of(row: dict) -> int:
    return int(row.get("schema", 1))


# ------------------------------------------------------------------ scoring

def score(rows: list[dict], predict) -> dict:
    tp = fp = tn = fn = abstain = unreplayable = 0
    for r in rows:
        gt_vuln = r.get("ground_truth") == "vulnerable" or r.get("expected") == "vulnerable"
        p = predict(r)
        if p is None:
            if or_gate(r) is None:
                abstain += 1
            else:
                unreplayable += 1
            continue
        if gt_vuln and p:
            tp += 1
        elif gt_vuln and not p:
            fn += 1
        elif not gt_vuln and p:
            fp += 1
        else:
            tn += 1
    scored = tp + fp + tn + fn
    out = {"tp": tp, "fp": fp, "tn": tn, "fn": fn, "scored": scored,
           "abstain": abstain, "unreplayable": unreplayable}
    out["fpr"] = fp / (fp + tn) if (fp + tn) else None
    out["recall"] = tp / (tp + fn) if (tp + fn) else None
    out["precision"] = tp / (tp + fp) if (tp + fp) else None
    if out["precision"] and out["recall"]:
        out["f1"] = 2 * out["precision"] * out["recall"] / (out["precision"] + out["recall"])
    else:
        out["f1"] = None
    return out


def load_rows(ckpt_dir: Path) -> list[dict]:
    rows = []
    for f in sorted(ckpt_dir.glob("*.json")):
        try:
            rows.append(json.load(open(f)))
        except Exception:  # noqa: BLE001 — a corrupt checkpoint is not a crash
            print(f"  ! unreadable checkpoint: {f.name}", file=sys.stderr)
    return rows


# ------------------------------------------------------------------ reporting

def line(label: str, s: dict) -> str:
    return (f"  {label:<30} {s['tp']:>4} {s['fp']:>4} {s['tn']:>4} {s['fn']:>4}   "
            f"FPR {fmt_ci(s['fp'], s['fp'] + s['tn']) if (s['fp'] + s['tn']) else '—':<22} "
            f"R {fmt_ci(s['tp'], s['tp'] + s['fn']) if (s['tp'] + s['fn']) else '—'}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--checkpoints", required=True, type=Path,
                    help="directory of per-contract checkpoint JSONs")
    ap.add_argument("--against", type=Path, default=None,
                    help="a committed benchmark_by_tier*.json to diff against")
    ap.add_argument("--tau", type=float, default=DEFAULT_TAU)
    ap.add_argument("--json", type=Path, default=None, help="write the recomputed report here")
    args = ap.parse_args()

    if not args.checkpoints.is_dir():
        print(f"no such directory: {args.checkpoints}", file=sys.stderr)
        return 2

    rows = load_rows(args.checkpoints)
    if not rows:
        print(f"no checkpoints in {args.checkpoints}", file=sys.stderr)
        return 2

    schemas = defaultdict(int)
    for r in rows:
        schemas[schema_of(r)] += 1

    print(f"\n{len(rows)} checkpoints in {args.checkpoints}")
    print(f"schema versions: {dict(sorted(schemas.items()))}")
    if schemas.get(1):
        print(f"\n  !! {schemas[1]} rows are schema 1 — they store n_findings but NOT")
        print("     per-finding confidences, so the shipped noisy-OR rule cannot be")
        print("     replayed over them at any tau. Those rows are counted as")
        print("     'unreplayable' below, not as abstentions.")

    by_tier = defaultdict(list)
    for r in rows:
        by_tier[r.get("tier")].append(r)

    print(f"\n{'':32}{'tp':>4} {'fp':>4} {'tn':>4} {'fn':>4}")
    print("  " + "-" * 100)

    recomputed = {"tau": args.tau, "n_rows": len(rows), "schemas": dict(schemas), "per_tier": {}}
    for _bucket, tier, _exp in TIER_ORDER:
        tr = by_tier.get(tier, [])
        if not tr:
            continue
        o = score(tr, or_gate)
        n = score(tr, lambda r: noisy_or(r, args.tau))
        print(line(f"{tier}  OR-gate", o))
        print(line(f"{tier}  noisy-OR tau={args.tau}", n))
        print()
        recomputed["per_tier"][tier] = {"or_gate": o, "noisy_or": n}

    o_all = score(rows, or_gate)
    n_all = score(rows, lambda r: noisy_or(r, args.tau))
    print("  " + "-" * 100)
    print(line("OVERALL  OR-gate", o_all))
    print(line(f"OVERALL  noisy-OR tau={args.tau}", n_all))
    recomputed["overall"] = {"or_gate": o_all, "noisy_or": n_all}

    if n_all["unreplayable"]:
        print(f"\n  !! {n_all['unreplayable']} rows could not be replayed under the shipped")
        print("     rule. Any noisy-OR figure above is over a SMALLER denominator than")
        print("     the OR-gate figure beside it, and the two are not comparable.")

    rc = 0
    if args.against:
        ref = json.load(open(args.against))
        print(f"\nDiff against {args.against.name}")
        print(f"  reported n_total={ref.get('n_total')} partial={ref.get('partial')}")
        ro = ref.get("overall", {})
        claimed = (ro.get("tp"), ro.get("fp"), ro.get("tn"), ro.get("fn"))
        for name, s in (("OR-gate", o_all), (f"noisy-OR tau={args.tau}", n_all)):
            got = (s["tp"], s["fp"], s["tn"], s["fn"])
            mark = "MATCH  " if got == claimed else "differs"
            print(f"  {mark} reported {claimed}  vs recomputed {name} {got}")
        if claimed not in ((o_all["tp"], o_all["fp"], o_all["tn"], o_all["fn"]),
                           (n_all["tp"], n_all["fp"], n_all["tn"], n_all["fn"])):
            print("\n  FAIL — the committed report matches NEITHER rule recomputed from")
            print("  these checkpoints. Either the checkpoints are not the ones that")
            print("  produced it, or the report was written by a path that no longer")
            print("  exists. Do not cite the committed figure until this resolves.")
            rc = 1

    if args.json:
        json.dump(recomputed, open(args.json, "w"), indent=2)
        print(f"\nwrote {args.json}")

    return rc


if __name__ == "__main__":
    raise SystemExit(main())
