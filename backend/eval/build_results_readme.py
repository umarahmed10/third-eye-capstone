def load(*parts):
    p = os.path.join(*parts)
    if not os.path.exists(p):
        return None
    with io.open(p, encoding='utf-8') as fh:
        return json.load(fh)


def load_snapshot():
    """The shipped-rule replay lives in the committed frontend snapshot.

    It is the artefact the deployed exhibit renders, so it is the same source
    the paper quotes. Parsed out of the .ts by brace-matching rather than
    duplicated into another JSON, so the two can never drift apart.
    """
    p = os.path.join(HERE, '..', '..', 'frontend', 'src', 'data', 'benchmark.ts')
    if not os.path.exists(p):
        return None
    txt = io.open(p, encoding='utf-8').read()
    # Anchor on the export, not on the first brace in the file: the leading
    # `import type { BenchmarkStats }` would otherwise be matched instead.
    k = txt.find('BENCHMARK_SNAPSHOT')
    i = txt.find('{', k if k >= 0 else 0)
    if i < 0:
        return None
    depth = 0
    for j in range(i, len(txt)):
        if txt[j] == '{':
            depth += 1
        elif txt[j] == '}':
            depth -= 1
            if depth == 0:
                try:
                    return json.loads(txt[i:j + 1])
                except Exception:
                    return None
    return None


def wilson(k, n, z=1.96):
    """95% Wilson score interval, as percentages.

    Wald is not used anywhere in this project: its width collapses to zero at
    p=0 or p=1, which is precisely where several of these rates sit.
    """
    if not n:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    m = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (100 * (c - m) / d, 100 * (c + m) / d)


def rate(k, n):
    if not n:
        return 'n/a'
    lo, hi = wilson(k, n)
    return '%.1f%% [%.1f, %.1f]' % (100 * k / n, lo, hi)


